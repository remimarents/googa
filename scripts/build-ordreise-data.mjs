import { mkdir, writeFile } from "node:fs/promises";
import { spawn } from "node:child_process";
import { promisify } from "node:util";
import { execFile } from "node:child_process";

const run = promisify(execFile);
const out = "ordreise";
const sources = {
  afsoomali: "https://raw.githubusercontent.com/yahyaqowle/Afsoomali/main/Somali-Words/Somali-Words.txt",
  kaikki: "https://kaikki.org/dictionary/Somali/kaikki.org-dictionary-Somali.jsonl",
  wikipedia: "https://dumps.wikimedia.org/sowiki/latest/sowiki-latest-pages-articles.xml.bz2"
};

const normalize = (value) => String(value)
  .replace(/[¹²³]/g, "")
  .normalize("NFKD")
  .replace(/\p{M}/gu, "")
  .trim()
  .toUpperCase();
const usable = (value, min = 2) => {
  const word = normalize(value);
  return /^[A-Z]+$/.test(word) && word.length >= min && word.length <= 8 ? word : null;
};
const canMake = (word, letters) => {
  const stock = new Map();
  for (const letter of letters) stock.set(letter, (stock.get(letter) || 0) + 1);
  for (const letter of word) {
    const remaining = stock.get(letter) || 0;
    if (!remaining) return false;
    stock.set(letter, remaining - 1);
  }
  return true;
};
const js = (name, value) => `// Generated by scripts/build-ordreise-data.mjs. Do not edit manually.\nwindow.${name}=${JSON.stringify(value)};\n`;

function bunzip(buffer) {
  return new Promise((resolve, reject) => {
    const process = spawn("bzip2", ["-dc"]);
    const chunks = [];
    let error = "";
    process.stdout.on("data", (chunk) => chunks.push(chunk));
    process.stderr.on("data", (chunk) => { error += chunk; });
    process.on("error", reject);
    process.on("close", (code) => code === 0 ? resolve(Buffer.concat(chunks).toString("utf8")) : reject(new Error(error || `bzip2 exited ${code}`)));
    process.stdin.end(buffer);
  });
}

function frequencyFromWiki(xml) {
  const counts = new Map();
  const text = xml
    .replace(/<[^>]+>/g, " ")
    .replace(/\{\{[^{}]*\}\}/g, " ")
    .replace(/https?:\/\/\S+/g, " ");
  for (const token of text.match(/[A-Za-z]{2,}/g) || []) {
    const word = usable(token);
    if (word) counts.set(word, (counts.get(word) || 0) + 1);
  }
  return counts;
}

const [afsoomaliRaw, kaikkiRaw, wikipediaArchive] = await Promise.all(
  Object.values(sources).map(async (url) => {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`Could not fetch ${url}: ${response.status}`);
    return url.endsWith(".bz2") ? Buffer.from(await response.arrayBuffer()) : response.text();
  })
);

const afsoomali = new Set((await afsoomaliRaw).split(/\r?\n/).map((word) => usable(word)).filter(Boolean));
const kaikkiRows = (await kaikkiRaw).split(/\r?\n/).filter(Boolean).map(JSON.parse);
const kaikkiMeta = new Map();
for (const row of kaikkiRows) {
  const word = usable(row.word);
  if (!word) continue;
  if (!kaikkiMeta.has(word)) kaikkiMeta.set(word, new Set());
  kaikkiMeta.get(word).add(row.pos || "unknown");
}
const kaikki = new Set(kaikkiMeta.keys());
const kaikkiAdditions = [...kaikki].filter((word) => !afsoomali.has(word)).sort();
const combined = new Set([...afsoomali, ...kaikki]);
const wikiCounts = frequencyFromWiki(await bunzip(wikipediaArchive));
const rank = (word) => wikiCounts.get(word) || 0;
const isKnownNameOnly = (word) => {
  const tags = kaikkiMeta.get(word);
  return Boolean(tags && [...tags].every((tag) => tag === "name"));
};
const candidates = [...combined]
  .filter((word) => word.length >= 3 && word.length <= 8)
  .filter((word) => !isKnownNameOnly(word))
  .sort((a, b) => rank(b) - rank(a) || a.localeCompare(b));

const levels = [];
const usedSeeds = new Set();
for (const seed of candidates.filter((word) => word.length >= 4 && word.length <= 7)) {
  if (levels.length >= 300 || usedSeeds.has(seed)) break;
  const found = candidates
    .filter((word) => word.length >= 3 && word.length <= seed.length && canMake(word, seed))
    .sort((a, b) => rank(b) - rank(a) || b.length - a.length || a.localeCompare(b));
  if (!found.includes(seed)) found.unshift(seed);
  const words = [...new Set(found)].slice(0, 8);
  if (words.length < 3) continue;
  usedSeeds.add(seed);
  levels.push({ id: levels.length + 1, letters: [...seed], words });
}

const reviewWords = candidates.slice(0, 1500).map((word, index) => ({
  no: index + 1,
  word,
  source: afsoomali.has(word) && kaikki.has(word) ? "Afsoomali + Kaikki" : afsoomali.has(word) ? "Afsoomali" : "Kaikki",
  frequency: rank(word),
  decision: "",
  note: ""
}));

await mkdir(out, { recursive: true });
await writeFile(`${out}/wordbank.js`, js("GOOGA_ORDREISE_WORDS", [...combined].sort()), "utf8");
await writeFile(`${out}/levels.js`, js("GOOGA_ORDREISE_LEVELS", levels), "utf8");
await writeFile(`${out}/data-sources.json`, JSON.stringify({
  generatedAt: new Date().toISOString(),
  sources,
  counts: { afsoomali: afsoomali.size, kaikki: kaikki.size, kaikkiAdditions: kaikkiAdditions.length, combined: combined.size, levels: levels.length, reviewWords: reviewWords.length }
}, null, 2) + "\n", "utf8");
await writeFile(`${out}/kaikki-additions.txt`, `${kaikkiAdditions.join("\n")}\n`, "utf8");
await writeFile(`${out}/review-words.tsv`, ["Nr\tSomali ord\tKilde\tWikipedia-treff\tGodkjent?\tMerknad", ...reviewWords.map((row) => [row.no, row.word, row.source, row.frequency, row.decision, row.note].join("\t"))].join("\n") + "\n", "utf8");

const rows = reviewWords.map((row) => `<tr><td>${row.no}</td><td><strong>${row.word}</strong></td><td>${row.source}</td><td>${row.frequency || "–"}</td><td>☐ Ja&nbsp;&nbsp;☐ Nei</td><td></td></tr>`).join("\n");
const html = `<!doctype html><html><head><meta charset="utf-8"><style>body{font:10pt Arial;color:#172033;margin:20mm}h1{color:#087f89;margin:0 0 4mm}p{line-height:1.35}table{border-collapse:collapse;width:100%;font-size:8.5pt}th,td{border:1px solid #b8c4cc;padding:4px;vertical-align:top}th{background:#dff7f7;text-align:left}tr{page-break-inside:avoid}</style></head><body><h1>Googa Ordreise – ord til faglig godkjenning</h1><p><strong>Til Harab:</strong> Dette er de første 1 500 kandidatordene for den somaliske Ordreise-utvidelsen i Googa. Kryss av <em>Ja</em> dersom ordet er et vanlig og passende ord i et barnevennlig ordspill. Skriv gjerne en bedre form eller merknad i siste kolonne. Egennavn, støtende ord, svært lokale former og tekniske/foreldede ord bør normalt avvises.</p><p>Ordbanken er bygd fra Afsoomali som hovedkilde, supplert med Kaikki/Wiktionary. «Wikipedia-treff» brukes kun til å prioritere vanlige ord; det er ikke en fasit for om et ord er korrekt.</p><table><thead><tr><th>Nr.</th><th>Ord</th><th>Kilde</th><th>Wikipedia-treff</th><th>Vurdering</th><th>Merknad / bedre form</th></tr></thead><tbody>${rows}</tbody></table></body></html>`;
await mkdir("docs", { recursive: true });
await writeFile("docs/Harab-googa-ordreise-ordliste.html", html, "utf8");
await run("textutil", ["-convert", "docx", "-output", "docs/Harab-googa-ordreise-ordliste.docx", "docs/Harab-googa-ordreise-ordliste.html"]);
